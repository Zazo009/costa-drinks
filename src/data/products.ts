const INTL_LOCALES: Record<string, string> = {
  es: 'es-ES',
  en: 'en-GB',
  fr: 'fr-FR',
  de: 'de-DE',
  ar: 'ar-SA',
};

export function formatPrice(cents: number, locale: string) {
  return new Intl.NumberFormat(INTL_LOCALES[locale] ?? 'en-GB', {
    style: 'currency',
    currency: 'EUR',
  }).format(cents / 100);
}
